// Builds the single-file game: inlines the stylesheet and scripts referenced by
// game/src/index.html into game/index.html. No dependencies.
//
//   node build.mjs           write game/index.html
//   node build.mjs --check   exit 1 if game/index.html is not up to date
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(fileURLToPath(import.meta.url));
const srcDir = join(root, 'game', 'src');
const outFile = join(root, 'game', 'index.html');
const read = file => readFileSync(join(srcDir, file), 'utf8').replace(/\r\n/g, '\n');

function inline(tag, file, wrap) {
  if (!existsSync(join(srcDir, file))) throw new Error(`${tag} references missing file game/src/${file}`);
  // A literal closing tag inside the content would end the inline block early.
  const body = read(file).trimEnd();
  if (body.includes(`</${wrap}`)) throw new Error(`game/src/${file} contains </${wrap}`);
  return `<${wrap}>\n${body}\n</${wrap}>`;
}

let html = read('index.html')
  .replace(/<link rel="stylesheet" href="([^"]+)">/g, (tag, file) => inline(tag, file, 'style'))
  .replace(/<script src="([^"]+)"><\/script>/g, (tag, file) => inline(tag, file, 'script'));
html = html.replace('<html lang="ko">',
  '<html lang="ko">\n<!-- Generated by build.mjs from game/src/ — edit those files, then run `node build.mjs`. -->');

if (process.argv.includes('--check')) {
  const current = existsSync(outFile) ? readFileSync(outFile, 'utf8').replace(/\r\n/g, '\n') : '';
  if (current !== html) {
    console.error('game/index.html is out of date. Run `node build.mjs` and commit the result.');
    process.exit(1);
  }
  console.log('game/index.html is up to date.');
} else {
  writeFileSync(outFile, html);
  console.log(`wrote game/index.html (${html.length} chars)`);
}
